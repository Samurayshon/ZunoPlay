create table public.xp_rules (
  source text primary key,
  min_xp integer not null check (min_xp >= 0),
  max_xp integer not null check (max_xp >= min_xp),
  default_xp integer not null check (default_xp between min_xp and max_xp),
  daily_limit integer check (daily_limit is null or daily_limit > 0),
  lifetime_limit integer check (lifetime_limit is null or lifetime_limit > 0),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

